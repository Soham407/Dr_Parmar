        <!-- Match before/after image heights while keeping aspect ratio (no cropping) -->
        <script>
        (function(){
            function matchPairHeights(){
                var rows = document.querySelectorAll('.before-after .row');
                rows.forEach(function(row){
                    // only handle rows with exactly two .col-md-6 columns (pairs)
                    var cols = row.querySelectorAll('.col-md-6');
                    if(cols.length !== 2) return;
                    var imgA = cols[0].querySelector('img');
                    var imgB = cols[1].querySelector('img');
                    if(!imgA || !imgB) return;

                    // reset any previous inline sizing so naturalWidth/naturalHeight compute correctly
                    imgA.style.width = '';
                    imgA.style.height = '';
                    imgB.style.width = '';
                    imgB.style.height = '';

                    var colWidth = cols[0].clientWidth;

                    function computeAndApply(){
                        var nwA = imgA.naturalWidth || imgA.width;
                        var nhA = imgA.naturalHeight || imgA.height;
                        var nwB = imgB.naturalWidth || imgB.width;
                        var nhB = imgB.naturalHeight || imgB.height;
                        if(!nwA || !nwB) return; // wait until images have dimensions

                        // scaled heights when images are fit to column width
                        var scaledHA = nhA * (colWidth / nwA);
                        var scaledHB = nhB * (colWidth / nwB);

                        // choose the smaller scaled height so both fit the column width without overflow
                        var targetH = Math.min(scaledHA, scaledHB);

                        // apply height (px) and let width adjust to keep aspect ratio
                        [imgA, imgB].forEach(function(img){
                            img.style.height = Math.round(targetH) + 'px';
                            img.style.width = 'auto';
                            img.style.display = 'block';
                            img.style.margin = '0 auto';
                        });
                    }

                    if(imgA.complete && imgB.complete){
                        computeAndApply();
                    } else {
                        var loaded = 0;
                        var cb = function(){ loaded++; if(loaded >= 2) computeAndApply(); };
                        if(!imgA.complete) imgA.addEventListener('load', cb); else loaded++;
                        if(!imgB.complete) imgB.addEventListener('load', cb); else loaded++;
                        if(loaded >= 2) computeAndApply();
                    }
                });
            }

            var resizeTimer;
            window.addEventListener('load', matchPairHeights);
            window.addEventListener('resize', function(){ clearTimeout(resizeTimer); resizeTimer = setTimeout(matchPairHeights, 150); });
            // run shortly after load in case images load slowly
            setTimeout(matchPairHeights, 600);
        })();
        </script>
       
