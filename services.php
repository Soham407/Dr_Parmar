                        <div class="content">
                          <p>Because we live longer and more stressful lives today, we are exposing our teeth to many more years of potentially damaging habits such as clenching, grinding, and chewing on hard objects.</p>
                            <p>These habits make our teeth more susceptible to cracks. Your endodontist may treat a cracked tooth to prevent further damage to the tooth structure and tissue.</p>
                            <p>Cracked teeth do not always show any visible signs of damage, but may present a variety of symptoms, including erratic pain when you chew with them, and pain or sensitivity to heat and cold. In many cases, the pain may come and go, making it difficult for your doctor to locate the source.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >WHY CRACKED TEETH HURT</button>    
