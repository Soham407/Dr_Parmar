                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>Choosing a dentist who “clicks” with you and your family is important, and you may wish to consider several dentists before making your final decision. During your first visit, you should be able to determine whether the dentist is right for you. During your appointment, consider the following:</p>
                            
                            <ul>
                                <li>Is the appointment schedule convenient?</li>
                                <li>Is the office easy to get to and close by?</li>
                                <li>Does the office appear to be clean and orderly?</li>
                                <li>Was your medical and dental history recorded and placed in a permanent file?</li>
                                <li>Does the dentist explain techniques for good oral health?</li>
