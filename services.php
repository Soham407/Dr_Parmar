                        <div class="content">
                          <p>Gum disease, known as periodontal disease, is a chronic inflammatory disease that affects the gums and bone supporting the teeth. It is a serious inflammatory disorder that, if left untreated, can lead to tooth loss.</p>
                            <p>Some of the factors that may contribute to gingivitis include:</p>
                            <ul>
                                <li>Poor oral hygiene</li>
                                <li>Smoking</li>
                                <li>Aging</li>
                                <li>Genetic predisposition</li>
                                <li>Systemic diseases and conditions such as diabetes or HIV</li>
                                <li>Stress</li>
                                <li>Inadequate nutrition</li>
                                <li>Puberty</li>
                                <li>Hormonal fluctuations</li>
                                <li>Pregnancy</li>
                                <li>Substance abuse</li>
                                <li>Certain medication use</li>
                            </ul>
                            
                            <p>While it is possible to have periodontal disease and not know it, some symptoms can include:</p>
                            <ul>
                                <li>Gums that bleed easily</li>
                                <li>Red, swollen, tender gums</li>
                                <li>Gums that have pulled away from the teeth</li>
                                <li>Persistent bad breath or bad taste</li>
                                <li>Pus between your teeth and gums</li>
                                <li>Permanent teeth that are loose or separating</li>
