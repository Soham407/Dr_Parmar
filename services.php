                       </div>
                       
                        <div class="content">
                          <p>There are many different types of cracked teeth. The treatment and outcome for your tooth depends on the type, location, and extent of the crack.</p>
                            
                        </div>
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >CRAZE LINES</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>Craze lines are tiny cracks that affect only the outer enamel. These cracks are extremely common in adult teeth. Craze lines are very shallow, cause no pain, and are of no concern beyond appearance.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >FRACTURED CUSP</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>When a cusp (the pointed part of the chewing surface) becomes weakened, a fracture sometimes results. The weakened cusp may break off by itself or have to be removed by the endodontist. When this happens, the pain will usually be relieved. A fractured cusp rarely damages the pulp, so root canal treatment is seldom needed. Your tooth will usually be restored with a full crown by your dentist.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >CRACKED TOOTH</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>Some cracks extend from the chewing surface of the tooth vertically towards the root. A cracked tooth may not be completely separated into two distinct segments. Because of the position of the crack, damage to the pulp is common. Root canal treatment is frequently needed to treat the injured pulp.</p>
                            <p>Your dentist will restore your tooth with a crown to hold the pieces together and protect the cracked tooth. At times, the crack may extend below the gingival tissue line, which requires extraction.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >SPLIT TOOTH</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>A split tooth is often the result of long-term progression of a cracked tooth. The split tooth is identified by a crack with distinct segments that can be separated. A split tooth cannot be saved intact. The position and extent of the crack, however, will determine whether a part of the tooth can be saved. In rare instances, endodontic treatment and a crown or other restoration by your dentist may be used to save a portion of the tooth.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >VERTICAL ROOT FRACTURE</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>Vertical root fractures are cracks that begin in the root of the tooth and extend toward the chewing surface. They often show minimal signs and symptoms and may therefore go unnoticed until the surrounding bone and gum become infected. Treatment may entail extraction of the tooth. However, endodontic surgery is sometimes appropriate if a portion of the tooth can be saved by removal of the fractured root.</p>
                            
                        </div>
                       
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >PREVENTING CRACKED TEETH </button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                          <p>While cracked teeth are not completely preventable, you can take some steps to make your teeth less susceptible to cracks.</p>
                            <ul>
                                <li>Don't chew on hard objects such as ice, unpopped popcorn kernels, or pens.</li>
                                <li>Don't clench or grind your teeth.</li>
                                <li>Wear a mouthguard or protective mask when playing contact sports.</li>
                            </ul>
                            <p>Early diagnosis is important. Even with high magnification and special lighting, it can be challenging to determine the extent of a crack. A cracked tooth that is not treated will progressively worsen, and eventually result in the loss of the tooth. Early diagnosis and treatment are essential in saving these teeth.</p>
                            
