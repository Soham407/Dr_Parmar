                       <button type="button" style="border:none;background:none;" >HOW CAN I TAKE CARE OF MY TEETH BETWEEN DENTAL CHECKUPS?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <ul>
                                <li>ALWAYS remember to brush your teeth at least two times a day, and floss at least once!</li>
                                <li>Make sure to use toothpaste that contains fluoride, and ask your dentist if you need a fluoride rinse. This will help prevent cavities.</li>
                                <li>Avoid foods with a lot of sugar (sugar increases the amount of bacteria that grows in your mouth causing more plaque and possibly cavities) and avoid tobacco (this can stain your teeth, cause gum disease, and eventually lead to oral cancer).</li>
                                <li>Don't be afraid to brush your tongue! By brushing your tongue, you will remove food particles and reduce the amount of plaque-causing bacteria. Tongue brushing also helps keep your breath fresh.</li>
                                <li>Be sure to schedule your routine checkup. It is recommended that you visit the dentist every six months.</li>
                                
                            </ul>
                        </div>
                       
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >AT WHAT AGE SHOULD I START TAKING MY CHILD TO SEE THE DENTIST?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>The American Academy of Pediatric Dentistry (AAPD) recommends that children first see a dentist as early as six months of age and no later than one year of age. During this time, your child's baby teeth will be coming in and your dentist can examine the health of your child's first few teeth. After the first visit, be sure to schedule regular checkups every six months.</p>
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >HOW OFTEN SHOULD I SEE THE DENTIST?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>Children, teens, and adults should all see the dentist for a regular checkup at least once every six months. Patients who are at a greater risk for oral cancer or gum disease may be required to see the dentist more than just twice a year. Your doctor will help determine how often you should visit the dentist for regular checkups.</p>
                        </div>

                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >WHAT IS A CAVITY?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>A cavity is a small hole that forms inside the tooth because of tooth decay. Cavities are formed when plaque buildup on the outside of the tooth combines with sugars and starches in the food you eat. This produces an acid that can eat away the enamel on your tooth. If a cavity is left untreated, it can lead to more serious oral health problems. Cavities can be prevented by remembering to brush your teeth at least two times a day and floss between teeth at least once.</p>
                        </div>
                       
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >WHAT IS A FILLING?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>A filling is a synthetic material that your dentist uses to fill a cavity after all of the tooth decay has been removed. Fillings do not generally hurt because your dentist will numb your mouth with an anesthetic. Fillings are made from a variety of different materials, including composites, gold, or ceramic. If you need a filling, be sure to talk to your doctor about what type is best for you and your teeth.</p>
                        </div>
                       
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >HOW OFTEN SHOULD I BRUSH MY TEETH?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>According to your dentist and the American Dental Association, you should brush your teeth at least two times a day. Brushing keeps your teeth, gums, and mouth clean and healthy by removing bacteria-causing plaque. It is also recommended that you use a soft-bristled toothbrush and toothpaste that contains fluoride when you brush your teeth. You should spend at least a minute on the top teeth and a minute on the bottom teeth, and remember to brush your tongue; it will help keep your breath smelling fresh!</p>
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >WHEN SHOULD I CHANGE MY TOOTHBRUSH?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>Your toothbrush will eventually wear out, especially if you are brushing your teeth twice a day for two to three minutes each time. Your dentist recommends that adults and children change their toothbrush every three months. If you are using an electric toothbrush, be sure to read the directions because you may not need to change toothbrush heads as frequently. Patients with gum disease are encouraged to change their toothbrush every four to six weeks to keep any bacteria from spreading. After brushing, rinse your toothbrush with hot water to kill germs and keep the bristles clean. If you've been sick, be sure to change your toothbrush as soon as possible.</p>
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >WHAT IS GUM DISEASE?</button>    
                            <i class="fa fa-arrow-down" style="float:right;color:#fff"></i>

                       </div>
                       
                        <div class="content">
                            <p>Also known as periodontal disease, gum disease is mostly caused by plaque and bacteria buildup that is not treated in its early stage. Other causes of periodontal disease include tobacco use, teeth grinding, some medications, and genetics. Gingivitis is the beginning stage of gum disease, and, if detected, is treatable. Gingivitis left untreated may turn into gum disease.</p>
                            <p>Advanced gum disease will lead to tooth and bone loss, and is a permanent condition. Brushing your teeth regularly and visiting the dentist every six months will help prevent gingivitis and more severe cases of periodontal disease. Common signs of gum disease:</p>
                            <ul>
                                <li>Red, irritated, bleeding, or swollen gums</li>
                                <li>Chronic bad breath</li>
                                <li>Loose teeth, or loss of teeth</li>
                                <li>Extreme tooth sensitivity</li>
                                <li>Receding gum line</li>
                                <li>Abscessed teeth</li>
                            </ul>
                        </div>
                       
                       
                       
                       <div class="collapsible">
