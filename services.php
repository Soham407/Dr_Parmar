                       </div>
                       
                        <div class="content">
                          <p>When the outer hard tissues of the tooth are cracked, chewing can cause movement of the pieces, and the pulp becomes irritated. When biting pressure is released, the crack can close quickly, resulting in a momentary, sharp pain. Irritation of the dental pulp can be repeated many times by chewing.</p>
                            <p>Eventually, the pulp will become damaged to the point where it can no longer heal itself. The tooth will not only hurt when chewing but may also become sensitive to extreme temperatures. In time, a cracked tooth may begin to hurt all by itself. Extensive cracks will lead to infection of the pulp tissue, even spreading to the bone and gum tissue that surrounds the tooth.</p>
                            
                        </div>
                       
                       
                       <div class="collapsible">
                       <button type="button" style="border:none;background:none;" >TYPES OF CRACKED TEETH</button>    
